// Regenerates pinyin.js from macOS's Mandarin transliteration:
//   swift scripts/generate-pinyin.swift > pinyin.js
import Foundation

var groups: [String: String] = [:]
for code in 0x4E00...0x9FFF {
    let char = String(UnicodeScalar(code)!)
    guard let latin = char.applyingTransform(.mandarinToLatin, reverse: false)?
        .applyingTransform(.stripDiacritics, reverse: false)?.lowercased(),
        latin.range(of: "^[a-z]+$", options: .regularExpression) != nil else { continue }
    groups[latin, default: ""] += char
}
let table = groups.keys.sorted().map { "\($0):\(groups[$0]!)" }.joined(separator: "|")
print("// Generated by scripts/generate-pinyin.swift. Maps pinyin syllables to Chinese characters.")
print("const PINYIN_TABLE = '\(table)';")
